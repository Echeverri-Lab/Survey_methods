"""
reconcile_stream_b.py
=====================

Joins the Stream B log, the manual codes, and the Crossref/OpenAlex check into
one table with a single status per record, and writes the summary report.

Usage:  python reconcile_stream_b.py
Reads:  stream_b_log.csv, stream_b_manual_codes.csv, stream_b_verification.csv
Writes: stream_b_reconciled.csv, stream_b_summary.md
"""
from __future__ import annotations

import csv
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Book entries match on title only (Crossref mostly returns reviews of the book),
# so a title match counts as verified for books, chapters, standards, and software.
TITLE_ONLY_TYPES = {"book", "chapter", "standard", "software", "grey"}

# Metadata errors confirmed by comparing the registry record with our citation.
KNOWN_FIXES = {
    "B056": "Year: the Internet, Phone, Mail, and Mixed-Mode Surveys edition is 2014 (4th ed.), not 2011",
    "B070": "DOI 10.1111/cobi.14384 resolves to a different paper (Yasué 2024); find correct DOI",
    "B147": "Year: published 2016 (Conservation Biology 30(2)), not 2014",
    "B009": "Title differs from registered title ('AIn't Nothing But a Survey?…', Heyde et al. 2025)",
}

# Registry returned a later reprint or a different record; citation checked by hand and is correct.
CHECKED_OK = {"B124", "B141"}


def missing_authors(ref: str) -> bool:
    head = ref.split("(")[0]
    return ref.startswith('"') or not re.search(r"\b[A-Z]\.|[A-Z][a-z]+\.? \(", head + " (")


def status(c, v):
    if c["flag"] == "duplicate":
        return "merge_duplicate"
    if c["flag"] == "placeholder":
        return "placeholder_needs_full_citation"
    if c["flag"] == "suspect":
        return "suspect_verify_against_source"
    if v["record_id"] in KNOWN_FIXES:
        return "fix_metadata"
    if v["record_id"] in CHECKED_OK:
        return "verified"
    verdict = v["verdict"]
    if verdict in ("no_confident_match", "doi_not_registered", "doi_title_mismatch"):
        return "not_found_verify_manually"
    if c["doc_type"] in TITLE_ONLY_TYPES:
        return "verified_title"
    if v["author_agrees"] == "False":
        return "fix_metadata"  # citation lacks authors or names the wrong first author
    if v["year_agrees"] == "False":
        return "fix_metadata"
    return "verified"


def main():
    log = {r["record_id"]: r for r in csv.DictReader(open(HERE / "stream_b_log.csv"))}
    codes = {r["record_id"]: r for r in csv.DictReader(open(HERE / "stream_b_manual_codes.csv"))}
    ver = {r["record_id"]: r for r in csv.DictReader(open(HERE / "stream_b_verification.csv"))}
    rows = []
    for rid, r in log.items():
        c, v = codes[rid], ver[rid]
        note = "; ".join(x for x in (c["note"], KNOWN_FIXES.get(rid, "")) if x)
        if status(c, v) == "fix_metadata" and not note:
            note = "Citation is missing authors" if missing_authors(r["reference"]) else "Author or year disagrees with registry record"
        rows.append({
            "record_id": rid, "reference": r["reference"], "doc_type": c["doc_type"], "role": c["role"],
            "status": status(c, v), "duplicate_of": c["duplicate_of"],
            "in_streamA_395": r["in_streamA_395"], "in_streamA_1580": r["in_streamA_1580"],
            "registry_title": v["match_title"], "registry_doi": v["match_doi"] or r["doi"],
            "registry_year": v["match_year"], "cited_in_files": r["cited_in_files"], "note": note,
        })
    with open(HERE / "stream_b_reconciled.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    st, role = Counter(r["status"] for r in rows), Counter(r["role"] for r in rows)
    unique = [r for r in rows if r["status"] != "merge_duplicate"]
    usable = [r for r in unique if r["status"] in ("verified", "verified_title", "fix_metadata")]
    methodish = [r for r in usable if r["role"] in ("method", "instrument", "standard")]
    ov395 = sum(r["in_streamA_395"] == "True" for r in unique)
    ov1580 = sum(r["in_streamA_1580"] == "True" for r in unique)
    lines = [
        "# Stream B rebuild — summary",
        "",
        "Generated by `reconcile_stream_b.py`. Source list: `master_reference_list_all_steps.md` "
        "(every unique reference cited across the repository's Step folders).",
        "",
        "## What the 242 actually is",
        "",
        f"- Entries in the list: **{len(rows)}**",
        f"- Duplicates of another entry (short + full form, or two editions): **{st['merge_duplicate']}** → unique works: **{len(unique)}**",
        f"- Overlap with the Stream A 395-record sample (DOI or exact title): **{ov395}** (manuscript reports 32)",
        f"- Overlap with the full 1,580-record Stream A corpus: **{ov1580}**",
        "",
        "## Status of each entry",
        "",
        "| Status | n | Meaning |",
        "|---|---|---|",
        f"| verified | {st['verified']} | Article; DOI or bibliographic match agrees on title, first author, and year |",
        f"| verified_title | {st['verified_title']} | Book/chapter/standard/grey; title found in registry (author/year not checkable this way) |",
        f"| fix_metadata | {st['fix_metadata']} | Work exists, but our citation has missing authors, wrong year, or wrong DOI |",
        f"| not_found_verify_manually | {st['not_found_verify_manually']} | No confident registry match; check by hand |",
        f"| suspect_verify_against_source | {st['suspect_verify_against_source']} | Details conflict with the real paper (likely mis-attributed or non-existent) |",
        f"| placeholder_needs_full_citation | {st['placeholder_needs_full_citation']} | Short form or note, e.g. '(General Reference for…)'; not a citation |",
        f"| merge_duplicate | {st['merge_duplicate']} | Same work as another entry |",
        "",
        "## What the entries are (role, all 242)",
        "",
        "| Role | n |",
        "|---|---|",
        *[f"| {k} | {role[k]} |" for k in ("method", "instrument", "standard", "theory", "example")],
        "",
        "- *method* = survey, psychometric, analysis, or ethics methodology; *instrument* = scale development/validation; "
        "*standard* = reporting standard or institutional guideline; *theory* = primary source for a social/behavioral theory "
        "(mostly from `Step_02/theory_summary.md`); *example* = empirical study used as a worked example.",
        f"- Usable now or after a metadata fix (verified, verified_title, fix_metadata): **{len(usable)}**, "
        f"of which methodological guidance, instruments, or standards: **{len(methodish)}**.",
        "",
        "## Consequences for the manuscript",
        "",
        "1. Table S2's breakdown (45 texts / 112 citation chasing / 62 standards / 23 author corpus) is not derived from any record; "
        f"only {role['standard']} entries are reporting standards or institutional documents, and no citation-chasing log exists.",
        f"2. The 32-record overlap should be {ov395}; five records labelled 'A+B' were matched against the repository's own RIS export, not Stream A.",
        "3. Stream B as currently defined is 'what the repository cites', which mixes methodological guidance with theory primary sources and worked examples. "
        "It cannot be described as an independent bottom-up search without a documented procedure (see `STREAM_B_PROTOCOL.md`).",
        "4. The suspect and placeholder entries sit in public repository files and must be fixed regardless of the review method "
        "(citation accuracy).",
    ]
    (HERE / "stream_b_summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
